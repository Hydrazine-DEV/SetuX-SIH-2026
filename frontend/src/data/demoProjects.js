/** Merge API project payload with demo fields missing from backend schema. */
export function enrichProject(apiData, projectId) {
  const id = projectId || apiData?.project_id;
  const demoProj = DEMO_PROJECTS.find(p => p.project_id === id);
  if (demoProj) return { ...demoProj, ...apiData };
  return apiData;
}

export function enrichProjects(apiList) {
  if (!Array.isArray(apiList)) return apiList;
  return apiList.map(p => enrichProject(p, p.project_id));
}
